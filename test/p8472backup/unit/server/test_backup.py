def _record(object_type: int, body: bytes) -> tuple[Object, BytesIO]:
    # Use deterministic IDs for the objects generated by the test client.
    object_id = sha256(bytes((object_type,)) + body).digest()
    return Object(object_type, object_id, len(body)), BytesIO(body)


def _file_records(path: Path) -> list[tuple[Object, BytesIO]]:
    records: list[tuple[Object, BytesIO]] = []
    with path.open("rb") as source:
        while chunk := source.read(_CHUNK_SIZE):
            records.append(_record(TYPE_DATA, DataContent(COMPRESSION_NONE, len(chunk), chunk).to_plaintext()))
    metadata = MetaContent(path.name.encode("utf-16"), tuple(obj.object_id for obj, _ in records))
    meta_record = _record(TYPE_METADATA, metadata.to_plaintext())
    root = SnapshotRootContent(b"client backup configuration", (meta_record[0].object_id,))
    records.extend((meta_record, _record(TYPE_SNAPSHOT, root.to_plaintext())))
    return records


def _read_fixture_file(snapshot: Snapshot, repository: Repository, index: LocationIndex, lock: RepositoryLock) -> bytes:
    bodies: dict[ObjectId, bytes] = {}
    for object_id in snapshot.object_catalog.object_ids:
        location = index.get(object_id)
        assert location is not None
        pack = lock.require_held_for(repository.packs_root / str(_KEY_ID) / f"{location.pack_id}.pack")
        output = BytesIO()
        assert Pack.read_object(pack, location.offset, location.length, output).object_id == object_id
        bodies[object_id] = output.getvalue()
    root = SnapshotRootContent.from_plaintext(bodies[snapshot.root_id])
    assert root.description == b"client backup configuration"
    (metadata_id,) = root.metadata_ids
    metadata = MetaContent.from_plaintext(bodies[metadata_id])
    assert metadata.metadata.decode("utf-16") == "report.txt"
    return b"".join(DataContent.from_plaintext(bodies[chunk_id]).data for chunk_id in metadata.chunk_ids)


@pytest.mark.parametrize(
    ("updated", "new_objects"),
    (
        pytest.param(b"shared!!second!!", 3, id="changed-chunk"),
        pytest.param(_ORIGINAL + b"append!!", 3, id="appended-chunk"),
        pytest.param(b"shared!!", 2, id="removed-chunk"),
        pytest.param(_ORIGINAL, 0, id="unchanged-file"),
    ),
)
def test_backup_and_incremental_backup_restore_both_file_versions(tmp_path: Path, backup_repository: tuple[ServerFacade, Repository], updated: bytes, new_objects: int) -> None:
    facade, repository = backup_repository
    path = tmp_path / "report.txt"
    path.write_bytes(_ORIGINAL)
    original_records = _file_records(path)
    original = facade.backup(_CLIENT_ID, _SET_ID, iter(original_records), prune="")

    path.write_bytes(updated)
    updated_records = _file_records(path)
    current = facade.backup(_CLIENT_ID, _SET_ID, iter(updated_records), prune="")
    assert current.snapshot_id != original.snapshot_id
    assert current.root_id == updated_records[-1][0].object_id
    reused = updated_records[0][0].object_id
    assert reused == original_records[0][0].object_id
    assert updated_records[0][1].tell() == 0
    assert updated_records[-1][1].tell() == updated_records[-1][0].length

    opened = RepositoryAdminService.find_by_client_id(tmp_path, _CLIENT_ID)
    assert opened.snapshots == {original, current}
    snapshots = SnapshotService()
    original = snapshots.get_snapshot(opened, _SET_ID, original.snapshot_id)
    current = snapshots.get_snapshot(opened, _SET_ID, current.snapshot_id)
    assert original.object_catalog.object_ids == {obj.object_id for obj, _ in original_records}
    assert current.object_catalog.object_ids == {obj.object_id for obj, _ in updated_records}
    assert len(current.object_catalog.object_ids - original.object_catalog.object_ids) == new_objects

    directory = repository.packs_root / str(_KEY_ID)
    assert Pack.load_from(directory / "1.pack").object_count == len(original_records)
    assert {path.name for path in directory.glob("*.pack")} == ({"1.pack", "2.pack"} if new_objects else {"1.pack"})
    if new_objects:
        assert Pack.load_from(directory / "2.pack").object_count == new_objects
    with RepositoryLock(opened.path) as lock:
        index = LocationIndex.load_from(opened.index_directory / str(_KEY_ID), lock)
        location = index.get(reused)
        assert location is not None and location.pack_id == 1
        assert _read_fixture_file(original, opened, index, lock) == _ORIGINAL
        assert _read_fixture_file(current, opened, index, lock) == updated
    facade.check(_CLIENT_ID)


def test_restore_keeps_the_selected_index_and_repository_lock_for_the_context(backup_repository: tuple[ServerFacade, Repository]) -> None:
    facade, repository = backup_repository
    facade.add_backup_set(_CLIENT_ID, _OTHER_SET_ID, _OTHER_KEY_ID)
    snapshot = facade.backup(_CLIENT_ID, _OTHER_SET_ID, iter(((_ROOT, BytesIO(_ROOT_BODY)),)), prune="")
    original_load = LocationIndex.load_from
    loaded_indexes: list[ReferenceType[LocationIndex]] = []

    def track_index_load(path: Path, lock: RepositoryLock) -> LocationIndex:
        assert path == repository.index_directory / str(_OTHER_KEY_ID)
        index = original_load(path, lock)
        loaded_indexes.append(ref(index))
        return index

    with patch.object(LocationIndex, "load_from", side_effect=track_index_load), facade.restore(_CLIENT_ID, _OTHER_SET_ID, snapshot.snapshot_id) as reader:
        assert reader.root_id == _ROOT.object_id
        (index_ref,) = loaded_indexes
        assert index_ref() is not None
        with pytest.raises(BlockingIOError), RepositoryLock(repository.path):
            pytest.fail("Restore did not hold the repository lock")

    gc.collect()
    assert index_ref() is None
    with RepositoryLock(repository.path) as lock:
        lock.require_held()


