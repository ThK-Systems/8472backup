@pytest.mark.parametrize("root_is_indexed", (False, True))
@pytest.mark.parametrize("root_body", (pytest.param(_ROOT_BODY, id="small-root"), pytest.param(b"r" * (128 * 1024 + 1), id="multi-block-root")))
def test_backup_finishes_at_the_end_of_the_root_body(backup_repository: tuple[ServerFacade, Repository], root_is_indexed: bool, root_body: bytes) -> None:
    facade, _ = backup_repository
    root = Object(TYPE_SNAPSHOT, _ROOT.object_id, len(root_body))
    if root_is_indexed:
        facade.backup(_CLIENT_ID, _SET_ID, iter(((root, BytesIO(root_body)),)), prune="")
    body = BytesIO(root_body + b"next frame")
    read = body.read

    def read_block(size: int | None = -1, /) -> bytes:
        assert size is not None and 0 < size <= 64 * 1024
        return read(size)

    def records() -> Iterator[tuple[Object, BinaryIO]]:
        yield _DATA, BytesIO(b"d")
        yield root, body
        pytest.fail("The backup read another record after the final root")

    with patch.object(body, "read", side_effect=read_block):
        snapshot = facade.backup(_CLIENT_ID, _SET_ID, records(), prune="")
    assert snapshot.root_id == root.object_id
    assert snapshot.object_catalog.object_ids == {_DATA.object_id, root.object_id}
    assert body.read() == b"next frame"


@pytest.mark.parametrize("root_is_indexed", (False, True))
@pytest.mark.parametrize("auto_cleanup", (False, True))
@pytest.mark.parametrize("disconnected", (False, True))
def test_backup_requires_the_last_root_byte(backup_repository: tuple[ServerFacade, Repository], root_is_indexed: bool, auto_cleanup: bool, disconnected: bool) -> None:
    facade, repository = backup_repository
    if root_is_indexed:
        facade.backup(_CLIENT_ID, _SET_ID, iter(((_ROOT, BytesIO(_ROOT_BODY)),)), prune="")
    register = repository.path / SNAPSHOT_REGISTRY_NAME
    index = repository.index_directory / str(_KEY_ID)
    register_before = register.read_bytes()
    index_before = index.read_bytes()
    body = BytesIO(_ROOT_BODY[:-1])
    read = body.read

    def read_until_interrupted(size: int | None = -1, /) -> bytes:
        data = read(size)
        if disconnected and not data:
            raise OSError("Client disconnected while sending the snapshot root")
        return data

    records = iter(((_DATA, BytesIO(b"d")), (_ROOT, body)))
    error_type = OSError if disconnected else ValueError
    reason = "Client disconnected" if disconnected else "Truncated object body"
    with patch.object(body, "read", side_effect=read_until_interrupted), pytest.raises(error_type, match=reason):
        facade.backup(_CLIENT_ID, _SET_ID, records, prune="", auto_cleanup=auto_cleanup)

    assert body.tell() == _ROOT.length - 1
    assert register.read_bytes() == register_before
    assert index.read_bytes() == index_before
    assert facade.cleanup(_CLIENT_ID, _SET_ID) == (0 if auto_cleanup else 1)
    retried = facade.backup(_CLIENT_ID, _SET_ID, iter(((_DATA, BytesIO(b"d")), (_ROOT, BytesIO(_ROOT_BODY)))), prune="")
    assert retried.object_catalog.object_ids == {_DATA.object_id, _ROOT.object_id}
    facade.check(_CLIENT_ID)


def _kill_backup_at_last_root_byte(storage_root: Path) -> None:
    body = BytesIO(_ROOT_BODY[:-1])
    read = body.read

    def read_or_kill(size: int | None = -1, /) -> bytes:
        data = read(size)
        if not data:
            os.kill(os.getpid(), signal.SIGKILL)
        return data

    with patch.object(body, "read", side_effect=read_or_kill):
        facade = ServerFacade(storage_root, server_fqdn=_SERVER_FQDN)
        facade.backup(_CLIENT_ID, _SET_ID, iter(((_DATA, BytesIO(b"d")), (_ROOT, body))), prune="")


@pytest.mark.parametrize("root_is_indexed", (False, True))
def test_cleanup_after_a_process_dies_mid_root(backup_repository: tuple[ServerFacade, Repository], root_is_indexed: bool) -> None:
    facade, repository = backup_repository
    if root_is_indexed:
        facade.backup(_CLIENT_ID, _SET_ID, iter(((_ROOT, BytesIO(_ROOT_BODY)),)), prune="")
    register = repository.path / SNAPSHOT_REGISTRY_NAME
    register_before = register.read_bytes()
    process = get_context("spawn").Process(target=_kill_backup_at_last_root_byte, args=(repository.path.parent,))
    process.start()
    try:
        process.join(timeout=10)
        assert process.exitcode == -signal.SIGKILL
    finally:
        if process.is_alive():
            process.kill()
            process.join()
        process.close()

    assert register.read_bytes() == register_before
    reopened = ServerFacade(repository.path.parent, server_fqdn=_SERVER_FQDN)
    assert reopened.cleanup(_CLIENT_ID, _SET_ID) == 1
    assert register.read_bytes() == register_before
    reopened.check(_CLIENT_ID)
